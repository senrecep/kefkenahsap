"""Bake the "kefkenahsap.com" watermark into SVG path data (#169) so the server needs no font at runtime.

The text never changes, so it is shaped once (HarfBuzz, with kerning) from the site's Montserrat 600 and written as one
path in font units (y down, origin = baseline start) to src/lib/media/watermark-glyphs.ts.

    uv run --with fonttools --with brotli --with uharfbuzz python scripts/brand/watermark-glyphs.py
"""
import io
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

TEXT = "kefkenahsap.com"
ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src/app/fonts/Montserrat.woff2"
OUT = ROOT / "src/lib/media/watermark-glyphs.ts"

font = TTFont(SRC)
font.flavor = None
ttf = io.BytesIO()
font.save(ttf)

buf = hb.Buffer()
buf.add_str(TEXT)
buf.guess_segment_properties()
hb.shape(hb.Font(hb.Face(ttf.getvalue())), buf, {"kern": True, "liga": True})

glyphs = font.getGlyphSet()
order = font.getGlyphOrder()
svg = SVGPathPen(glyphs, ntos=lambda v: f"{round(v, 1):g}")
bounds = BoundsPen(glyphs)
x = 0
for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
    name = order[info.codepoint]
    # Font units are y-up; SVG is y-down.
    glyphs[name].draw(TransformPen(svg, (1, 0, 0, -1, x + pos.x_offset, -pos.y_offset)))
    glyphs[name].draw(TransformPen(bounds, (1, 0, 0, -1, x + pos.x_offset, -pos.y_offset)))
    x += pos.x_advance

x0, y0, x1, y1 = bounds.bounds
OUT.write_text(
    f"""// Generated by scripts/brand/watermark-glyphs.py from src/app/fonts/Montserrat.woff2 (600, SIL OFL 1.1). Do not edit.
// "{TEXT}" in font units, y down, origin at the start of the baseline.
export const WATERMARK_GLYPHS = {{
  text: '{TEXT}',
  unitsPerEm: {font['head'].unitsPerEm},
  ascender: {font['hhea'].ascent},
  descender: {font['hhea'].descent},
  advance: {x},
  ink: {{ x0: {x0:g}, y0: {y0:g}, x1: {x1:g}, y1: {y1:g} }},
  d: '{svg.getCommands()}',
}} as const
"""
)
print(f"wrote {OUT.relative_to(ROOT)}: advance={x} ink=({x0:g},{y0:g})-({x1:g},{y1:g})")
